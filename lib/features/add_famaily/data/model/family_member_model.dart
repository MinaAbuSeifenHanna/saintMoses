  copyWith({
    String? fullName,
    String? nationalId,
    String? phoneNumber,
    String? address,
    String? assistance,
    String? pension,
    String? diocese,
    String? fatherBishop,
    String? church,
    String? area,
    String? assistanceAmount,
    String? dataForWidowsAndOrphans,
    String? theDeceased,
    String? itWorks,
    String? valueOfPension,
    String? sourcesOfIncome,
    String? propertyOrLeases,

    String? dateOfSearch,
    String? fatherName ,
    String? fatherPhone ,
    String? fatherReport,
    String? serverName,
    String? serverPhone,
    String? writtenBy,
    int? numberOfSons ,
}) {
    return FamilyMemberModel(
        fullName: fullName ?? this.fullName,
        nationalId: nationalId ?? this.nationalId,
        phoneNumber: phoneNumber ?? this.phoneNumber,
        address: address ?? this.address,
        assistance: assistance ?? this.assistance,
        pension: pension ?? this.pension,
        diocese: diocese ?? this.diocese,
        fatherBishop: fatherBishop ?? this.fatherBishop,
        church: church ?? this.church,
        area: area ?? this.area,
