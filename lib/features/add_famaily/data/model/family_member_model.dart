        required super.fatherName ,
        required super.fatherPhone ,
        required super.fatherReport,
        required super.serverName,
        required super.serverPhone,
        required super.writtenBy,
        required super.numberOfSons,
      });

  factory FamilyMemberModel.fromMap(Map<String, dynamic> map) {
    return FamilyMemberModel(
        fullName: map['fullName'],
        nationalId: map['nationalId'],
        phoneNumber: map['phoneNumber'],
        address: map['address'],
        assistance: map['assistance'],
        pension: map['pension'],
        diocese: map['diocese'],
        fatherBishop: map['fatherBishop'],
        church: map['church'],
        area: map['area'],
        assistanceAmount: map['assistanceAmount'],
        dataForWidowsAndOrphans: map['dataForWidowsAndOrphans'],
        theDeceased: map['theDeceased'],
        itWorks: map['itWorks'],
        valueOfPension: map['valueOfPension'],
        sourcesOfIncome: map['sourcesOfIncome'],
        propertyOrLeases: map['propertyOrLeases'],
        fatherName : map['fatherName'],
        dateOfSearch:  map['dateOfSearch'],
        fatherPhone:  map['fatherPhone'],
        fatherReport: map['fatherReport'],
        serverName:  map['serverName'],
        serverPhone: map['serverPhone'],
        writtenBy: map['writtenBy'],
        numberOfSons: map['numberOfSons'],
